export function translate(key: string, lang: Language = 'fr', fallback?: string): string {
  const dict = translations[lang] || translations.fr;
  if (dict && dict[key]) {
    return dict[key];
  }
  const fallbackDict = lang === 'fr' ? translations.en : translations.fr;
  if (fallbackDict && fallbackDict[key]) {
    return fallbackDict[key];
  }
  return fallback || key;
}

export function useTranslation() {
  const { lang, setLang } = useAuth();

  const t = (key: string, fallback?: string): string => {
    return translate(key, lang, fallback);
  };

  return {
    lang,
    setLang,
    t,
    isFr: lang === 'fr',
    isEn: lang === 'en',
    toggleLang: () => setLang(lang === 'fr' ? 'en' : 'fr'),
  };
}
